#!/usr/bin/env bun
// Regenerate the Herdr installer assets after editing themes, layout, mod or keys.
import { readdirSync, readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";

const root = resolve(import.meta.dir, "../targets/herdr");
const out = resolve(root, "assets.ts");
const paths = ["themes/muster.json", "themes/muster-day.json", "layouts/muster.json", "keys.json"];
const mod = resolve(root, "mods/muster");
for (const entry of readdirSync(mod, { withFileTypes: true })) {
  if (entry.isFile() && (entry.name.endsWith(".js") || entry.name === "mod.json")) paths.push(`mods/muster/${entry.name}`);
}
for (const entry of readdirSync(resolve(mod, "icons"), { withFileTypes: true })) {
  if (entry.isFile() && entry.name.endsWith(".svg")) paths.push(`mods/muster/icons/${entry.name}`);
}
paths.sort();
const assets = Object.fromEntries(paths.map((path) => [path, readFileSync(resolve(root, path), "utf8")]));
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `// Generated by bun run build-herdr-assets; do not edit.\nexport const HERDR_ASSETS: Record<string, string> = ${JSON.stringify(assets, null, 2)};\n`);
console.log(`wrote ${relative(root, out)} (${paths.length} assets)`);
